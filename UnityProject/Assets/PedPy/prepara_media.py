"""
prepara_media.py

Prepares the img/ and video/ folders of the questionnaire:
  - renames the files with neutral names (respondents must not read "navmesh" or
    "mlagent" in the address of an image or a video);
  - resizes the images to 1600 px and saves them as JPG (from a few MB to a few hundred KB);
  - crops the videos to the room (removing the black bands and the Unity panels on the sides)
    and compresses them to at most 720p, without audio, optimized for the web (requires ffmpeg).

Expected input names (produced by the existing scripts and by the video cutting):
  Part 1 images:     navmesh_baseline_vs_mlagent_01.png   -> img/p1_c01.jpg
  Part 2 images:     mlagent_06_vs_mlagent_10.png         -> img/p2_c06_c10.jpg
  reference video:   NavMeshAgent.mp4                     -> video/ref.mp4
  agent videos:      ML_Agent1.mp4 ... ML_Agent24.mp4     -> video/c01.mp4 ... video/c24.mp4
Video names such as ML_Agent01, mlagent_1 or navmesh are also accepted,
in the formats .mp4, .mov, .mkv, .avi, .webm (converted to .mp4).

Usage, from the Assets\\PedPy folder (where confronto_dist_tempo is):
  python prepara_media.py --immagini "confronto_dist_tempo\\traiettorie_sovrapposte" --video "<video folder>" --uscita "<questionnaire folder>"

  --immagini  folder with the path images generated by genera_overlay_coppie.py
  --video     folder with the cut videos (NavMeshAgent, ML_Agent1 ... ML_Agent24)
  --uscita    folder containing index.html: img\\ and video\\ are created there
Relative paths start from the folder where the command is run; if in doubt,
use full paths (C:\\...) in quotes.
"""

import argparse
import re
import shutil
import subprocess
from pathlib import Path

from PIL import Image

LARGHEZZA_MAX = 1600
QUALITA_JPG = 82
ALTEZZA_MAX_VIDEO = 720
# Crop of the videos to the room, as fractions of the frame (x, y, width, height).
# Measured on the top-view recordings: keeps the whole room with a small margin.
# Set to None to disable cropping.
RITAGLIO = (0.2266, 0.0347, 0.5273, 0.9444)

# Must match CONFIG in index.html
FASE1 = list(range(1, 25))   # 24 configurations
# Part 2: the 8 pairs, the same for everyone
FASE2 = [(6, 10), (5, 6), (23, 24), (2, 7), (22, 23), (19, 24), (8, 10), (1, 7)]

RE_IMG_P1 = re.compile(r"navmesh_baseline_vs_mlagent_(\d+)", re.I)
RE_IMG_P2 = re.compile(r"mlagent_(\d+)_vs_mlagent_(\d+)", re.I)
RE_VID_AGENTE = re.compile(r"ml[_\- ]?agent[_\- ]?(\d+)", re.I)        # ML_Agent1, ML_Agent01, mlagent_1
RE_VID_REF = re.compile(r"nav[_\- ]?mesh(?:[_\- ]?agent)?", re.I)       # NavMeshAgent, navmesh
ESTENSIONI_VIDEO = {".mp4", ".mov", ".mkv", ".avi", ".webm"}


def nome_immagine(stem):
    m = RE_IMG_P1.fullmatch(stem)
    if m:
        return f"p1_c{int(m.group(1)):02d}.jpg"
    m = RE_IMG_P2.fullmatch(stem)
    if m:
        return f"p2_c{int(m.group(1)):02d}_c{int(m.group(2)):02d}.jpg"
    return None


def nome_video(stem):
    m = RE_VID_AGENTE.fullmatch(stem)
    if m:
        return f"c{int(m.group(1)):02d}.mp4"
    if RE_VID_REF.fullmatch(stem):
        return "ref.mp4"
    return None


def cartella_ok(src: Path, cosa: str) -> bool:
    """Checks that the folder exists and reports it clearly if it does not."""
    if src.is_dir():
        print(f"  folder: {src.resolve()}")
        return True
    print(f"  ERROR: the {cosa} folder does not exist: {src.resolve()}")
    print("  Check the path: relative paths start from the folder where the command is run.")
    return False


def prepara_immagini(src: Path, dst: Path):
    if not cartella_ok(src, "images"):
        return
    dst.mkdir(parents=True, exist_ok=True)
    file = sorted(src.glob("*.png")) + sorted(src.glob("*.jpg"))
    if not file:
        print("  WARNING: no .png or .jpg images in this folder.")
    for f in file:
        nuovo = nome_immagine(f.stem)
        if not nuovo:
            print(f"  skipped (unrecognized name): {f.name}")
            continue
        img = Image.open(f).convert("RGB")
        if img.width > LARGHEZZA_MAX:
            altezza = round(img.height * LARGHEZZA_MAX / img.width)
            img = img.resize((LARGHEZZA_MAX, altezza), Image.LANCZOS)
        out = dst / nuovo
        img.save(out, "JPEG", quality=QUALITA_JPG, optimize=True, progressive=True)
        print(f"  {f.name} -> img/{nuovo} ({out.stat().st_size // 1024} KB)")


def prepara_video(src: Path, dst: Path):
    if not cartella_ok(src, "video"):
        return
    dst.mkdir(parents=True, exist_ok=True)
    ffmpeg = shutil.which("ffmpeg")
    if not ffmpeg:
        print("  ffmpeg not found: the videos are only copied and renamed, without cropping or compression.")
        print("  To install it: winget install --id Gyan.FFmpeg -e  (then reopen the terminal)")
    file = sorted(p for p in src.iterdir() if p.suffix.lower() in ESTENSIONI_VIDEO)
    if not file:
        print(f"  WARNING: no videos ({', '.join(sorted(ESTENSIONI_VIDEO))}) in this folder.")
    for f in file:
        nuovo = nome_video(f.stem)
        if not nuovo:
            print(f"  skipped (unrecognized name): {f.name}")
            continue
        out = dst / nuovo
        if ffmpeg:
            filtri = f"scale=-2:'min({ALTEZZA_MAX_VIDEO},ih)'"
            if RITAGLIO:
                x, y, w, h = RITAGLIO
                filtri = (f"crop=trunc(iw*{w}/2)*2:trunc(ih*{h}/2)*2:trunc(iw*{x}):trunc(ih*{y}),"
                          + filtri)
            cmd = [
                ffmpeg, "-y", "-loglevel", "error", "-i", str(f),
                "-vf", filtri,
                "-c:v", "libx264", "-preset", "slow", "-crf", "28",
                "-pix_fmt", "yuv420p", "-an", "-movflags", "+faststart",
                str(out),
            ]
            subprocess.run(cmd, check=True)
        else:
            if f.suffix.lower() != ".mp4":
                print(f"  WARNING: {f.name} is not an .mp4 and cannot be converted without ffmpeg")
            shutil.copy2(f, out)
        print(f"  {f.name} -> video/{nuovo} ({out.stat().st_size // 1024} KB)")


def controlla(dst_img: Path, dst_vid: Path):
    gruppi = {
        "Part 1 images": [dst_img / f"p1_c{n:02d}.jpg" for n in FASE1],
        "Part 2 images": [dst_img / f"p2_c{a:02d}_c{b:02d}.jpg" for a, b in FASE2],
        "videos": [dst_vid / "ref.mp4"] + [dst_vid / f"c{n:02d}.mp4" for n in FASE1],
    }
    tutti = [p for file in gruppi.values() for p in file]
    pronti = [p for p in tutti if p.exists()]
    totale_mb = sum(p.stat().st_size for p in pronti) / 1_048_576
    print(f"\nFiles ready: {len(pronti)}/{len(tutti)}, total {totale_mb:.0f} MB")
    for nome, file in gruppi.items():
        mancanti = [p.name for p in file if not p.exists()]
        if mancanti:
            print(f"  MISSING {len(mancanti)} {nome}: {', '.join(mancanti)}")
    for p in pronti:
        mb = p.stat().st_size / 1_048_576
        if mb > 25:
            print(f"  TOO LARGE for GitHub: {p.parent.name}/{p.name} ({mb:.0f} MB, the limit is 25 MB)")


def main():
    ap = argparse.ArgumentParser(description="Prepares the images and videos of the questionnaire")
    ap.add_argument("--immagini", type=Path, help="folder with the path images (png)")
    ap.add_argument("--video", type=Path, help="folder with the cut videos (mp4)")
    ap.add_argument("--uscita", type=Path, default=Path("."), help="questionnaire folder (default: current)")
    args = ap.parse_args()

    dst_img, dst_vid = args.uscita / "img", args.uscita / "video"
    print(f"Output: {args.uscita.resolve()}")
    if not (args.uscita / "index.html").exists():
        print("  Note: there is no index.html here. Move img\\ and video\\ next to index.html at the end.")
    if args.immagini:
        print("Images:")
        prepara_immagini(args.immagini, dst_img)
    if args.video:
        print("Videos:")
        prepara_video(args.video, dst_vid)
    controlla(dst_img, dst_vid)


if __name__ == "__main__":
    main()
